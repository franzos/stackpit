//! Commercial-tier license gate.
//!
//! The MIT core (everything outside this module) ships without any of the
//! capabilities listed in `MONETIZATION.md`. This module itself is governed by
//! `LICENSE-COMMERCIAL` at the repo root (Stackpit Commercial License 1.0, SPDX
//! `LicenseRef-Stackpit-Commercial-1.0`) — source-available, free for
//! development / evaluation / personal hobbyist use, requires a valid
//! Ed25519-signed Commercial License Key for production use, and forbids
//! operating Stackpit as a hosted service for third parties without a separate
//! agreement.
//!
//! Design:
//!
//! 1. **Offline-signed.** Licenses are Ed25519-signed CBOR blobs (see the
//!    `license-issuer` repo). Stackpit verifies against [`PUBLIC_KEY_BYTES`] —
//!    baked in at build time — and never phones home.
//!
//! 2. **Single-license model.** One signed blob per Stackpit install,
//!    persisted in the `stackpit_license` row (singleton PK). Activated via
//!    `/web/admin/license`; deactivation is a row DELETE.
//!
//! 3. **Lock-free reads.** The verified status sits behind an
//!    [`arc_swap::ArcSwap`] so every check is a single atomic pointer load.
//!
//! 4. **Grace period.** Expired licenses keep gated features visible but
//!    read-only for a fixed 30-day window ([`GRACE_DAYS`]) so a forgotten
//!    renewal doesn't blow up production.
//!
//! Two features are gated today: observability (the Prometheus `/metrics`
//! endpoint) and integrations (Slack, webhooks, and the issue trackers, whose
//! implementations live in [`providers`]). Adding another is a new
//! [`license::Feature`] variant plus its call-site gate.

